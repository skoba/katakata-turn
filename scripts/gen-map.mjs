import { geoEquirectangular, geoPath } from 'd3-geo';
import { readFile, writeFile } from 'node:fs/promises';

const target = new URL('../src/assets/world.ts', import.meta.url);
const source = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';
const projection = geoEquirectangular().scale(1000 / (2 * Math.PI)).translate([500, 250]);
const path = geoPath(projection).digits(2);
let data;
let attribution;
let fallback = false;
try {
  if (process.argv.includes('--fallback')) throw new Error('explicit fallback');
  const file = process.argv.find((arg) => arg.startsWith('--input='));
  if (file) data = JSON.parse(await readFile(file.slice(8), 'utf8'));
  else {
    const response = await fetch(source, { signal: AbortSignal.timeout(20_000) });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    data = await response.json();
  }
  if (data.type !== 'FeatureCollection' || !data.features?.length) throw new Error('invalid land data');
  attribution = 'Natural Earth 1:110m land / public domain; no borders or labels';
} catch (error) {
  fallback = true;
  // Coarse, hand-drawn land silhouettes. Rings are clockwise for d3-geo.
  const polygons = [
    [[-168,70],[-132,72],[-105,52],[-55,49],[-80,8],[-112,23],[-130,48],[-168,70]],
    [[-80,10],[-48,-2],[-35,-12],[-55,-55],[-74,-42],[-80,10]],
    [[-18,35],[15,37],[52,10],[35,-35],[14,-33],[-18,10],[-18,35]],
    [[-10,36],[-8,60],[45,72],[130,70],[178,57],[140,35],[118,3],[78,8],[45,35],[-10,36]],
    [[112,-12],[151,-10],[155,-30],[133,-41],[114,-29],[112,-12]],
    [[-56,60],[-25,60],[-20,82],[-45,83],[-56,60]],
  ];
  data = { type: 'FeatureCollection', features: polygons.map((ring) => ({ type: 'Feature', geometry: { type: 'Polygon', coordinates: [[...ring].reverse()] }, properties: {} })) };
  attribution = 'Hand-drawn coarse land fallback; no borders or labels';
  console.warn(`Map fallback: ${error.message}`);
}
const landPath = path(data);
if (!landPath) throw new Error('empty map');
await writeFile(target, `// Generated by scripts/gen-map.mjs. ${attribution}\nexport const mapWidth = 1000;\nexport const mapHeight = 500;\nexport const landPath = ${JSON.stringify(landPath)};\n`);
if (fallback) {
  const notes = new URL('../NOTES.md', import.meta.url);
  const line = '- 地図生成時にネットワークが利用できないため、同形式の手描き大陸フォールバックを生成する（再生成は npm run gen:map）。\n';
  const current = await readFile(notes, 'utf8');
  if (!current.includes(line.trim())) await writeFile(notes, current + line);
}
console.log(`Generated world.ts (${landPath.length} path characters)`);
